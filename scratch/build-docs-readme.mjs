// scratch/build-docs-readme.mjs — generate docs/README.slat, the self-describing
// index for the engineering/recovery shelf. "Read the README: what book is this,
// when you'd read it, what's in here." (Alfred, 2026-07-24 — one home for the
// most important books: the ones you rebuild the system from.)
//
// Buckets every file in docs/ by filename pattern. Prefers the .slat form and
// notes when a .md sibling is the archived render. No file is hidden or moved —
// this is a map, not a filter.
import { readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
const DOCS = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'docs')

const files = (await readdir(DOCS)).filter(f => f !== 'README.slat').sort()
const slatSet = new Set(files.filter(f => f.endsWith('.slat')))
const has = f => files.includes(f)

// pick canonical form: prefer .slat; if only .md exists, use it.
function canon (base) { return slatSet.has(base + '.slat') ? base + '.slat' : base + '.md' }

const RECOVERY = /-1\.0\.ENG|LANG-ENGINEERING|LANG-DESIGN|CORTEX|FORGE-1|HELLO-SURFACE|MARIONETTE|COMPOSER-1|COMPOSER-2|LOAM|LACUNA-INTEGRATION|SECURITY-CANONICAL|TELEMETRY-MEDIAN|LLM-AUGMENTED-REPL|MOTOI-TUI|SAKURA-.*-1\.0|SAKURA-VOICE|SAKURA-AUTOMATIONS|SAKURA-SCHEME-1|SAKURA-TRAINING|PERF-COMPOSER|COMPAT-ARCHITECTURE/
const DOCTRINE = /WEAVE-RECIPE|BOOK-TYPES|HOW-TO-REGISTER|EAGER-VS-LAZY|FIVE-ROWS-EXPLAINED|ENGINEERING-DECISIONS|ENGINEERING-CH-DECISIONS|SLAT-RENDERER|SLAT-TO-MD|RUNBOOK/
const JOURNAL = /EVAL-|AUDIT-|FOLD-|NIGHT-WORK|-REPORT|REVEAL|VERIFICATION|CHECKPOINT|FINALIZATION|COVERAGE|EXECUTION|GAP-CLOSURE|PROSE-LIFT|SAFETY|POLISH|WAVE|BURN-DOWN|RESEARCH-|CORPUS-|GRAPH-|LACAN|LIMA-|MK2-SFT|ISB-SFT|PAPER-|CPT-|SFT-|SIGNIFIER|PEDAGOGY|CONVERSATION-NOTES|WALKTHROUGH|KUDOS|MOTOI-3|MOTOI-4|MOTOI-5|MOTOI-MK|TREE-REBALANCE|BOOK-OF-|BOOK-COMPLETION|NO-NETWORKS|CLAUDE-TAKE|FINISHING-MOVE|3-GENERATIONS/

const bases = [...new Set(files.map(f => f.replace(/\.(slat|md)$/, '')))].sort()
const recovery = [], doctrine = [], journal = [], other = []
for (const b of bases) {
  const f = canon(b)
  if (RECOVERY.test(b)) recovery.push(f)
  else if (DOCTRINE.test(b)) doctrine.push(f)
  else if (JOURNAL.test(b)) journal.push(f)
  else other.push(f)
}

const line = f => `   (:doc ${JSON.stringify(f)})`
const shelf = (title, purpose, list) => list.length
  ? `\n  (shelf :title ${JSON.stringify(title)} :purpose ${JSON.stringify(purpose)} :count ${list.length}\n${list.map(line).join('\n')})` : ''

// docs/README.slatl — BOOT RECORD for the engineering & recovery shelf, per
// spec/BOOK-LAYOUT.slat. This is a SHELF (many independent recovery books),
// not a single ordered book: :nav groups the books into named shelves rather
// than a chapter sequence.
const out = `;; README.slatl — Motoi Engineering & Recovery Shelf · BOOT RECORD
;;
;; Boot record for the engineering & recovery shelf, per spec/BOOK-LAYOUT.slat.
;; This is the ONE home for the books you rebuild the system from. Generated by
;; scratch/build-docs-readme.mjs — regenerate after adding a doc. This shelf is a
;; collection of independent recovery books (not one ordered chapter sequence),
;; so :nav groups them into named shelves.
(dialect :applies ("motoi") :note "Boot record for the engineering & recovery shelf.")

(boot-record
  :book-title "Motoi Engineering & Recovery Shelf"
  :book-kind  "engineering-shelf"
  :book-slug  "motoi-engineering-recovery"
  :boot-into  "the recovery shelf below — start with the system-design books"
  :for        ("returning-collaborator" "llm-inference" "human-reader" "rosetta-render-target")
  :training-eligible #t
  :confidentiality "internal"
  :counts (:recovery ${recovery.length} :doctrine ${doctrine.length} :journal ${journal.length} :other ${other.length})

  :what-this-is
  "The design journal of the Motoi/Sakura/Lacuna system: how it is built and,
   more importantly, how to REBUILD it. These are the engineering & recovery
   books — the ones you reconstruct the system from if the authors are gone.
   One home, one shelf. Not the language itself (see :not-here)."

  :when-to-read
  "Read these to understand or reconstruct the system from scratch. If ever the
   authors go away, this shelf is the recovery plan: the system-design books
   first (what the pieces are and how they fit), then the method & doctrine (how
   we work), then the journal (why decisions were made — context, not spec)."

  :whats-inside
  "System-design & recovery books (${recovery.length}), method & doctrine (${doctrine.length}),
   the training/eval/audit journal (${journal.length}), and other notes (${other.length}).
   SLAT is canonical; where a .md sibling exists it is an archived render — the
   exception is LANG-ENGINEERING, authored as .md (never slat-render it)."

  :not-here
  "The LANGUAGE itself is not here. The Motoi language reference lives in
   scheme/reference/ (one chaptered book with its own boot record). The narrative
   learn-to-code books live in scheme-books/. The SRE operations manual lives in
   SRE-MANUAL/. Each is its own book folder."

  :nav
  (${shelf('Recovery & system-design books (read these to rebuild)', 'the specification you rebuild the system against', recovery)}${shelf('Method & doctrine (how we work)', 'the procedures and rules the work follows', doctrine)}${shelf('Journal — training/eval/audit history (context, not spec)', 'why decisions were made; not a spec', journal)}${shelf('Other', 'uncategorized notes', other)})

  :for-rosetta
  "This folder is the engineering shelf. Render this boot record as the landing
   page: the prose sections become the intro, :nav becomes grouped lists of book
   links (one per :doc, grouped by shelf :title). Prefer the .slat form of each
   doc; a .md sibling is an archived render.")
`

await writeFile(resolve(DOCS, 'README.slatl'), out, 'utf8')
console.log(`docs/README.slatl written. recovery=${recovery.length} doctrine=${doctrine.length} journal=${journal.length} other=${other.length}`)
if (other.length) console.log('OTHER (uncategorized):', other.join(', '))
