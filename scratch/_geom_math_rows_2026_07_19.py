VERB_START_RE = re.compile(r'^\(verb\b')
NAME_RE = re.compile(r':name\s+"([^"]+)"')

def enrich(path, data_dict):
    text = path.read_text()
    lines = text.split("\n")

    verb_starts = set(i for i, ln in enumerate(lines) if VERB_START_RE.match(ln))

    out_lines = []
    idx = 0
    inserted = 0
    skipped = []

    while idx < len(lines):
        if idx in verb_starts:
            # Find end of this verb block by paren-balance.
            depth = 0
            end_idx = None
            for j in range(idx, len(lines)):
                for ch in lines[j]:
                    if ch == "(":
                        depth += 1
                    elif ch == ")":
                        depth -= 1
                if depth == 0:
                    end_idx = j
                    break

            if end_idx is None:
                out_lines.append(lines[idx])
                idx += 1
                continue

            block = lines[idx:end_idx + 1]
            joined = "\n".join(block)
            m = NAME_RE.search(joined)
            name = m.group(1) if m else None

            if name and name in data_dict:
                rows = build_rows(name, data_dict[name])
                closing_line = block[-1]
                if closing_line.strip() == ")":
                    out_lines.extend(block[:-1])
                    out_lines.extend(rows.split("\n"))
                    out_lines.append(closing_line)
                else:
                    last_paren = closing_line.rfind(")")
                    head = closing_line[:last_paren].rstrip()
                    tail = closing_line[last_paren:]
                    out_lines.extend(block[:-1])
                    if head:
                        out_lines.append(head)
                    out_lines.extend(rows.split("\n"))
                    out_lines.append("  " + tail)
                inserted += 1
            else:
                out_lines.extend(block)
                if name:
                    skipped.append(name)

            idx = end_idx + 1
            continue

        out_lines.append(lines[idx])
        idx += 1

    path.write_text("\n".join(out_lines))
    return inserted, skipped


