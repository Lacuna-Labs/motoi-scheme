# Escape helper for embedding into SLAT strings.
def esc(s):
    return s.replace("\\", "\\\\").replace("\"", "\\\"")

def fmt_row(name, fields, per_disc):
    """fields: dict, per_disc: (eng, math, cs). Returns SLAT text."""
    lines = ["  :" + name + " ("]
    lines.append("    (" + " ".join(f":{k} \"{esc(v)}\"" for k, v in fields.items()) + ")")
    e, m, c = per_disc
    lines.append(f"    (:eng \"{esc(e)}\" :math \"{esc(m)}\" :cs \"{esc(c)}\"))")
    return "\n".join(lines)

def fmt_row3(name, setup, rungs, explanation, meta, per_disc):
    """Row 3 special: has :rungs sub-list."""
    lines = ["  :" + name + " ("]
    lines.append(f"    (:setup \"{esc(setup)}\"")
    lines.append("     :rungs (")
    for dom, code in rungs:
        lines.append(f"       (:domain \"{esc(dom)}\" :code \"{esc(code)}\")")
    lines.append("     )")
    lines.append(f"     :explanation \"{esc(explanation)}\"")
    lines.append(f"     :meta \"{esc(meta)}\")")
    e, m, c = per_disc
    lines.append(f"    (:eng \"{esc(e)}\" :math \"{esc(m)}\" :cs \"{esc(c)}\"))")
    return "\n".join(lines)

