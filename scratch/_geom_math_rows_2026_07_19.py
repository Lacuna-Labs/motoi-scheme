def find_verb_blocks(text):
    """Return list of (start_index, end_index, verb_name) for each (verb ...) block.
       end_index is the position of the outer closing ')'."""
    blocks = []
    i = 0
    while i < len(text):
        m = re.search(r'\(verb\b', text[i:])
        if not m:
            break
        start = i + m.start()
        # Match parens
        depth = 0
        j = start
        name = None
        in_str = False
        while j < len(text):
            c = text[j]
            if in_str:
                if c == '\\':
                    j += 2
                    continue
                if c == '"':
                    in_str = False
            else:
                if c == '"':
                    in_str = True
                elif c == '(':
                    depth += 1
                elif c == ')':
                    depth -= 1
                    if depth == 0:
                        break
                elif c == ';' :
                    # skip line comment
                    while j < len(text) and text[j] != '\n':
                        j += 1
                    continue
            j += 1
        # Extract name
        nm = re.search(r':name\s+"([^"]+)"', text[start:j+1])
        if nm:
            name = nm.group(1)
        blocks.append((start, j, name))
        i = j + 1
    return blocks


def enrich(path, data):
    text = path.read_text()
    blocks = find_verb_blocks(text)
    # Rewrite from end so offsets stay valid
    out = text
    missing = []
    added = 0
    for (s, e, name) in reversed(blocks):
        if name not in data:
            missing.append(name)
            continue
        # Skip if already enriched
        block = out[s:e+1]
        if ":row-2-audit" in block:
            continue
        rows_text = build_all_rows(name, data[name])
        # Insert BEFORE the final ')' at position e.
        # Find last non-whitespace char before e
        k = e - 1
        while k > s and out[k] in " \t\n":
            k -= 1
        # Insertion point is right after out[k] (before the trailing ws + ')')
        insert_pos = k + 1
        new_block_extra = "\n" + rows_text
        out = out[:insert_pos] + new_block_extra + out[insert_pos:]
        added += 1
    return out, added, missing


def main():
    for path, data, label in [(GEOM_PATH, GEOM, "geom"), (MATH_PATH, MATH, "math")]:
        print(f"Processing {label} ({path.name})...")
        new_text, added, missing = enrich(path, data)
        path.write_text(new_text)
        print(f"  enriched: {added}")
        if missing:
            print(f"  missing data: {missing}")

if __name__ == "__main__":
    main()
