// scratch/gen-std-specs.mjs — emit spec/<part>.slatl for each standard part.
//
// The spec files are gate #2 ("spec kept alongside"). Every record is
// DERIVED from the part module's already-authored META table + header
// provenance — nothing is invented here. Run: node scratch/gen-std-specs.mjs
import { writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

import * as core from '../lib/std/r7rs-completions-core.js'
import * as srfi1 from '../lib/std/srfi-1.js'
import * as srfi13 from '../lib/std/srfi-13.js'
import * as srfi125 from '../lib/std/srfi-125.js'
import * as srfi27 from '../lib/std/srfi-27.js'
import * as srfi133 from '../lib/std/srfi-133.js'

// Provenance — copied verbatim from each part file's header block.
