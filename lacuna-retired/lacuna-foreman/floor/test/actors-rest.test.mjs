// spec: A3 §4.12 streams and packets; A4 V-146, V-150, V-152; C-77 · class: M · technique: a burst · method: 1 text cube per 8 tokens;
// past 8/s the road samples and prints N; an error diamond flies 85 % and never lands; the road fades 1.2 s after the last landing;
// dur by length within 0.5–0.9 s · sre: does a packet's speed ever encode a value? (never)
test('answers ride one text cube per 8 tokens, a burst samples with the printed N, an error diamond never lands, a road fades 1.2 s after the last landing', () => {
  const sc = scenario()
  loadMind(sc, 'e4b', 1)
  sc.ev(10, 'mind.turn.start', 'e4b', { who: 'owner', session: 'eval:s', model: 'e4b', mode: 'desk' })
  for (let i = 1; i <= 20; i++) sc.ev(10 + i * 0.05, 'mind.turn.phase', 'e4b', { phase: 'answer', tokens: i * 8, n: 1, tps: 160 })
  const road = sc.at(11.1, 'road:text:e4b>desk')
  assert.ok(road, 'the road exists')
  assert.equal(road.count, 20)
  assert.ok(road.sampled > 1, `sampled 1 dot = ${road.sampled}`)
  assert.equal(sc.state(11.1, 'road:text:e4b>desk'), 'sampled')
  assert.equal(sc.cause(11.1, 'road:text:e4b>desk'), `1 dot = ${road.sampled}`)
  assert.ok(road.packets.length < 20, 'fewer packets than messages')
  const last = road.packets[road.packets.length - 1]
  assert.ok(last.dur >= 0.5 && last.dur <= 0.9)
  assert.equal(durOf(0), 0.5)
  assert.equal(durOf(200), 0.9)
  assert.ok(Math.abs(durOf(50) - 0.725) < 1e-9)
  assert.ok(['live', 'sampled'].includes(sc.state(last.t0 + last.dur + 1.1, 'road:text:e4b>desk')))
  assert.equal(sc.state(last.t0 + last.dur + 1.3, 'road:text:e4b>desk'), 'fading')
  assert.equal(sc.state(last.t0 + last.dur + 2.5, 'road:text:e4b>desk'), 'dormant')
  assert.equal((pose(sc.f, 'road:text:e4b>desk', last.t0 + last.dur + 2.5)[CH.flags] & FLAG.drawn), 0)
  startRun(sc, 'w-aaa111', 20, 'e4b')
  sc.ev(30, 'run.fail', 'w-aaa111', { why: 'deadline', exit: 15, step: 2 })
  const err = sc.at(30.1, 'road:diamond:w-aaa111>foreman')
  assert.ok(err && err.errors === 1)
  const pk = err.packets[0]
  const a = { x: 0, z: 0 }
  const b = { x: 100, z: 0 }
  const end = packetPose(pk, a, b, pk.t0 + pk.dur)
  assert.equal(end.lands, false, 'an error diamond never lands')
  assert.ok(end.x <= 85 + 1e-9, 'it flies 85 % of the road')
  assert.equal(end.alpha, 0, 'and fades out')
  const ok = packetPose({ ...pk, error: false }, a, b, pk.t0 + pk.dur)
  assert.equal(ok.lands, true)
  assert.equal(ok.x, 100)
  assert.equal(packetPose(pk, a, b, pk.t0).u, 0)
})
