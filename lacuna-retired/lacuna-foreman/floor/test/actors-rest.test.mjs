// spec: A3 §4.8; R4; C-13 · class: M · technique: probes · method: up, a 240 ms probe tick, slow 2 s on/off against a recorded
// budget, down takes the LME's minds to engine-down, stale at 3 × 30 s · sre: does the rack ever show green? (never)
test('a service is up on its probe, ticks for 240 ms, reads slow against a recorded budget, takes the LME\'s minds down with it, and goes stale at 90 s', () => {
  const sc = scenario()
  loadMind(sc, 'e4b', 1)
  sc.ev(5, 'service.up', 'lme', { pid: 500, 'rss-mb': 6000, at: 'desk.sock', 'p99-ms': 50, 'rss-budget-mb': 8000 })
  assert.equal(sc.state(5.5, 'svc:lme'), 'up')
  sc.ev(10, 'service.probe', 'lme', { ms: 3, up: true, pid: 500, 'rss-mb': 6100, code: null })
  assert.equal(sc.state(10.1, 'svc:lme'), 'probe')
  assert.equal(sc.state(10.5, 'svc:lme'), 'up')
  assert.ok(Math.abs(pose(sc.f, 'svc:lme', 10.5)[CH.fill] - (0.1 + 0.8 * 6100 / 8000)) < 1e-9, 'RSS against the budget')
  sc.ev(20, 'service.probe', 'lme', { ms: 900, up: true, pid: 500, 'rss-mb': 6100, code: null })
  assert.equal(sc.state(21.5, 'svc:lme'), 'up')
  assert.equal(sc.state(22.5, 'svc:lme'), 'slow')
  assert.match(sc.cause(22.5, 'svc:lme'), /p99 900 ms over 50/)
  sc.ev(30, 'service.probe', 'lme', { ms: 4, up: true, pid: 500, 'rss-mb': 6100, code: null })
  assert.equal(sc.state(31.5, 'svc:lme'), 'slow')
  assert.equal(sc.state(32.5, 'svc:lme'), 'up')
  sc.ev(40, 'service.down', 'lme', { 'was-pid': 500, why: 'probe' })
  assert.equal(sc.state(40.5, 'svc:lme'), 'down')
  assert.equal(sc.state(40.5, 'e4b'), 'engine-down')
  assert.equal(pose(sc.f, 'svc:lme', 40.5)[CH.edgeHue], 3, 'red')
  sc.ev(50, 'service.up', 'lme', { pid: 501, 'rss-mb': 100, at: 'desk.sock' })
  assert.equal(sc.state(50.5, 'svc:lme'), 'up')
  assert.equal(sc.state(50.5, 'e4b'), 'resident')
  assert.equal(sc.at(50.5, 'svc:lme').restarts, 0)
  assert.equal(sc.state(139, 'svc:lme'), 'up')
  assert.equal(sc.state(141, 'svc:lme'), 'stale')
  assert.equal(sc.state(1, 'svc:door'), null, 'no record, no actor')
})

// spec: A3 §4.9; C-14 mind.read · class: M · technique: reads · method: the library reads then shelves at 60 s; the web is absent
// until a read; cortex heat is a rate against the day's peak; the forge trains, pauses, cools; the desk follows the owner's turn ·
// sre: does the globe spin with nothing reading it? (never)
test('the library reads then shelves, the web appears only for a read, the cortex heats by rate, the forge trains and banks, the desk follows the owner\'s turn', () => {
  const sc = scenario()
  loadMind(sc, 'e4b', 1)
  assert.equal(sc.state(2, 'library'), 'shelved')
  assert.equal(sc.state(2, 'web'), 'absent')
  assert.equal((pose(sc.f, 'web', 2)[CH.flags] & FLAG.drawn), 0, 'the web is not drawn')
  assert.equal(sc.state(2, 'cortex'), 'cold')
  assert.match(sc.cause(2, 'cortex'), /unknown: no cortex-ops line yet/)
  sc.ev(10, 'mind.read', 'e4b', { from: 'library', what: 'the backup playbook', ms: 40 })
  assert.equal(sc.state(10.5, 'library'), 'read')
  assert.equal(sc.cause(10.5, 'library'), 'e4b reads the backup playbook')
  sc.ev(20, 'mind.read', 'e4b', { from: 'web', what: 'docs.example', ms: 400 })
  assert.equal(sc.state(20.5, 'web'), 'read')
  assert.ok((pose(sc.f, 'web', 20.5)[CH.flags] & FLAG.drawn) !== 0)
  sc.ev(30, 'cortex.ops', 'cortex', { n: 36, 'per-s': 3.6, 'node-put': 4, 'edge-put': 32, seq: 948300 })
  assert.equal(sc.state(30.5, 'cortex'), 'warm')
  assert.equal(sc.cause(30.5, 'cortex'), '36 ops/10 s')
  sc.ev(40, 'cortex.ops', 'cortex', { n: 72, 'per-s': 7.2, 'node-put': 8, 'edge-put': 64, seq: 948400 })
  sc.ev(45, 'cortex.recall', 'cortex', { hits: 8, by: 'e4b' })
  assert.equal(sc.state(45.2, 'cortex'), 'recall')
  assert.equal(pose(sc.f, 'cortex', 46)[CH.fill], 1, 'at the day\'s peak')
  sc.ev(50, 'forge.step', 'forge', { n: 420, total: 1200, loss: 1.84, secs: 10, model: 'e2b', stage: 'train' })
  assert.equal(sc.state(50.5, 'forge'), 'training')
  assert.equal(sc.cause(50.5, 'forge'), 'step 420/1200 · loss 1.84')
  sc.ev(60, 'forge.pause', 'forge', { job: 'job-1', by: 'broker', park: true })
  assert.equal(sc.state(60.5, 'forge'), 'paused')
  assert.equal(sc.cause(60.5, 'forge'), 'parked · banked')
  sc.ev(65, 'forge.resume', 'forge', { job: 'job-1', by: 'broker' })
  assert.equal(sc.state(65.5, 'forge'), 'training')
  assert.equal(sc.state(69.9, 'library'), 'read')
  assert.equal(sc.state(70.1, 'library'), 'shelved')
  assert.equal(sc.state(80, 'cortex'), 'cold')
  assert.equal(sc.state(82, 'web'), 'absent')
  sc.ev(90, 'mind.turn.start', 'e4b', { who: 'owner', session: 'eval:d', model: 'e4b', mode: 'desk' })
  assert.equal(sc.state(90.5, 'desk'), 'listening')
  sc.ev(91, 'mind.turn.phase', 'e4b', { phase: 'think', tokens: 0, n: 1 })
  assert.equal(sc.state(91.5, 'desk'), 'thinking')
  sc.ev(92, 'mind.turn.phase', 'e4b', { phase: 'answer', tokens: 8, n: 1, tps: 40 })
  assert.equal(sc.state(92.5, 'desk'), 'speaking')
  assert.equal(pose(sc.f, 'desk', 92.5)[CH.edgeHue], 5, 'lavender')
  sc.ev(93, 'mind.turn.done', 'e4b', { ms: 3000, tokens: 80, tps: 40, 'prefill-ms': 200, prompt: 300, reused: 0, reason: 'eos', slot: 0 })
  assert.equal(sc.state(93.5, 'desk'), 'rest')
  assert.equal(sc.state(1000, 'forge'), 'cold')
})

// spec: A3 §4.10, §4.11, §4.14; A2 §3.5, §3.8 · class: M · technique: ledger rows · method: a giant lit only by a row, away after
// 15 min; a failed call; a visitor talking 60 s then present then gone at 10 min; the owner quiet at 60 s with the 600 s note;
// a work order's states; the box's level · sre: is "on a call" ever a constant? (never)
