// kinds-compile.mjs — THE CATALOG'S TEXT FOR THE BROWSER (lane F5-A, unit A.1). Owns: writing `kinds-text.js` from `kinds.slat`,
// the catalog's text as one string constant, so `validate.js` reads the catalog with the one reader where no file system is
// (the browser) as where one is (the foreman, `node --test`). Refuses: any edit of its own: kinds.slat is the source, and
// `test/validate.test.mjs` fails when kinds-text.js is not its text, byte for byte. Implements: A2 §4.1 (the registry is data,
// read once). Invariants (design §18): none of its own. Faults (§16): none.
//
// Usage: node lacuna-foreman/floor/kinds-compile.mjs   (after every edit of kinds.slat)
import fs from 'node:fs'

const here = new URL('.', import.meta.url)
const text = fs.readFileSync(new URL('kinds.slat', here), 'utf8')
const out = '// kinds-text.js — GENERATED by kinds-compile.mjs from kinds.slat, the floor\'s kind catalog; do not edit (edit kinds.slat,\n' +
  '// then run `node lacuna-foreman/floor/kinds-compile.mjs`; test/validate.test.mjs fails when the two differ).\n\n' +
  '/** The text of kinds.slat, read by validate.js with the one reader. */\n' +
  `export const KINDS_SLAT = ${JSON.stringify(text)}\n`
fs.writeFileSync(new URL('kinds-text.js', here), out)
console.log(`kinds-text.js: ${text.length} characters of kinds.slat`)
