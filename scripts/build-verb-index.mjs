#!/usr/bin/env node
// build-verb-index.mjs — walk the loaded env after installCoreLazy and emit
// a machine-readable index of every verb: name, source lib, load mode.
//
// Output: _status/verb-index.slat  (SLAT so Motoi + humans can read it)
//
// Usage: node scripts/build-verb-index.mjs
import { makeBaseEnv } from '../src/base.js'
import { installCoreLazy } from '../core/index.js'
import { EAGER as _EAGER, LAZY as _LAZY } from '../core/verb-manifest.js'
import { writeFileSync } from 'node:fs'

const fuel = { n: 1_000_000 }
const env = makeBaseEnv(fuel)
const summary = installCoreLazy(env, { fuel })

// Reverse index: verb-name → { source, mode }
const index = new Map()

// Eager: after install() ran, every verb in env came from an eager module.
// We can't know exactly which without more scaffolding, so we mark them
// by exclusion — anything NOT in the lazy list is eager.
const lazyVerbSet = new Set()
for (const entry of _LAZY) {
  if (!entry.verbs) continue
  for (const v of entry.verbs) {
    lazyVerbSet.add(v)
    index.set(v, { source: entry.name, mode: 'lazy' })
  }
}

for (const [name] of env.vars) {
  if (index.has(name)) continue
  // Best-effort source attribution — anything not lazy is "eager (core)".
  index.set(name, { source: 'eager (core)', mode: 'eager' })
}

const rows = [...index.entries()].sort()
const lines = []
lines.push(';;; verb-index.slat — auto-generated by scripts/build-verb-index.mjs')
lines.push(';;; Every verb loaded by the Motoi runtime, its source module, and load mode.')
lines.push(';;; Do not hand-edit — regenerate after any verb-manifest.js change.')
lines.push('')
lines.push(`(index :generated ${JSON.stringify(new Date().toISOString())}`)
lines.push(`       :verb-count ${rows.length}`)
lines.push(`       :eager-count ${rows.filter(([, m]) => m.mode === 'eager').length}`)
lines.push(`       :lazy-count ${rows.filter(([, m]) => m.mode === 'lazy').length})`)
lines.push('')
for (const [name, meta] of rows) {
  lines.push(`(verb :name ${JSON.stringify(name)} :source ${JSON.stringify(meta.source)} :mode ${JSON.stringify(meta.mode)})`)
}

writeFileSync('/Users/alfred/code/motoi-scheme/_status/verb-index.slat', lines.join('\n') + '\n')
console.log(`Wrote ${rows.length} verbs to _status/verb-index.slat`)
console.log(`  Eager: ${rows.filter(([, m]) => m.mode === 'eager').length}`)
console.log(`  Lazy : ${rows.filter(([, m]) => m.mode === 'lazy').length}`)
